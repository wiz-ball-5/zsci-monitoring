def _build_catalog(records):
    df = pd.DataFrame(
        records,
        columns=["label", "start", "end", "peak_ym", "intensity", "etype"],
    )
    df["start"] = pd.to_datetime(df["start"])
    df["end"] = pd.to_datetime(df["end"])
    df["peak"] = pd.to_datetime(df["peak_ym"])
    # Notebook behavior: event label is the peak year.
    df["label"] = df["peak"].dt.year.astype(str)
    return df


